#!/usr/bin/env python3
"""Draw synthetic floor-plan sheets with Pillow.

The committed PNGs under ``samples/`` are generated by this script, so they
carry no third-party copyright (CC0). They are deliberately simple: walls,
room labels, dimensions, a unit-type title block and a small unit list —
enough to exercise the input adapters, the CV crop snapping and the HTML
verifiers without any real marketing material.

    python scripts/make_samples.py            # writes samples/<project>/*.png
    python scripts/make_samples.py --out DIR  # elsewhere
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
DEFAULT_OUT = HERE.parent / "samples"


def _font(size: int) -> ImageFont.ImageFont:
    for path in ("DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
                 "/usr/share/fonts/TTF/DejaVuSans.ttf", "/Library/Fonts/Arial.ttf",
                 "C:/Windows/Fonts/arial.ttf"):
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            continue
    return ImageFont.load_default()


def draw_unit(draw: ImageDraw.ImageDraw, origin: tuple[int, int], rooms: list[tuple[str, int, int, int, int, str]],
              wall: int = 6) -> tuple[int, int, int, int]:
    """Draw rooms as rectangles (x, y, w, h relative to origin). Returns the
    outer bounding box in absolute pixels."""
    ox, oy = origin
    small = _font(16)
    tiny = _font(12)
    xs, ys = [], []
    for label, x, y, w, h, area in rooms:
        x0, y0, x1, y1 = ox + x, oy + y, ox + x + w, oy + y + h
        xs += [x0, x1]
        ys += [y0, y1]
        draw.rectangle([x0, y0, x1, y1], outline="black", width=wall)
        draw.text((x0 + 10, y0 + 8), label, fill="black", font=small)
        draw.text((x0 + 10, y0 + 30), area, fill="#444", font=tiny)
        draw.text((x0 + w // 2 - 20, y1 - 18), f"{w * 10} mm", fill="#666", font=tiny)
    return min(xs), min(ys), max(xs), max(ys)


def unit_plan_sheet(path: Path, unit_type: str, title: str, rooms, area: str, beds: str,
                    units_list: list[str], size=(1600, 1200), bg="white") -> None:
    img = Image.new("RGB", size, bg)
    d = ImageDraw.Draw(img)
    big, mid, small = _font(36), _font(22), _font(16)
    d.text((60, 40), title, fill="black", font=big)
    d.text((60, 90), f"TYPE {unit_type}   {beds}   {area}", fill="black", font=mid)
    x0, y0, x1, y1 = draw_unit(d, (220, 180), rooms)
    # compass + scale bar
    d.ellipse([size[0] - 140, 60, size[0] - 60, 140], outline="black", width=3)
    d.polygon([(size[0] - 100, 70), (size[0] - 90, 110), (size[0] - 100, 100), (size[0] - 110, 110)], fill="black")
    d.text((size[0] - 106, 145), "N", fill="black", font=mid)
    d.rectangle([x0, y1 + 50, x0 + 200, y1 + 58], fill="black")
    d.text((x0, y1 + 64), "0        2 m", fill="black", font=small)
    # supplementary unit list under the drawing
    d.text((x0, y1 + 110), "Units: " + ", ".join(units_list), fill="black", font=small)
    d.text((60, size[1] - 50), "Synthetic sample generated by fpextract scripts/make_samples.py (CC0)",
           fill="#999", font=small)
    img.save(path, format="PNG", optimize=True)


def site_map_sheet(path: Path, title: str, blocks: list[tuple[str, int, int, str]], size=(1400, 1000)) -> None:
    img = Image.new("RGB", size, "#f6f1e7")
    d = ImageDraw.Draw(img)
    big, mid, small = _font(34), _font(20), _font(16)
    d.text((60, 40), title, fill="black", font=big)
    colors = {"A1": "#9fc5e8", "B2": "#b6d7a8", "C3": "#ffe599"}
    for label, x, y, ut in blocks:
        d.rectangle([x, y, x + 170, y + 110], fill=colors.get(ut, "#ddd"), outline="black", width=3)
        d.text((x + 12, y + 12), label, fill="black", font=mid)
        d.text((x + 12, y + 70), f"Type {ut}", fill="black", font=small)
    lx = size[0] - 260
    d.text((lx, 120), "Legend", fill="black", font=mid)
    for i, (ut, c) in enumerate(colors.items()):
        d.rectangle([lx, 160 + i * 36, lx + 26, 186 + i * 36], fill=c, outline="black")
        d.text((lx + 40, 162 + i * 36), f"Type {ut}", fill="black", font=small)
    d.text((60, size[1] - 50), "Synthetic sample generated by fpextract scripts/make_samples.py (CC0)",
           fill="#999", font=small)
    img.save(path, format="PNG", optimize=True)


def generate(out: Path) -> list[Path]:
    """Write the sample projects and a manifest. Returns the image paths."""
    paths: list[Path] = []
    hv = out / "harbour-view"
    hv.mkdir(parents=True, exist_ok=True)
    a1 = hv / "harbour-view-type-a1.png"
    unit_plan_sheet(
        a1, "A1", "Harbour View — Type A1 Floor Plan",
        rooms=[("LIVING / DINING", 0, 0, 420, 300, "28.5 sqm"),
               ("BEDROOM 1", 420, 0, 300, 300, "14.2 sqm"),
               ("KITCHEN", 0, 300, 220, 200, "8.0 sqm"),
               ("BATH", 220, 300, 200, 200, "4.5 sqm"),
               ("BEDROOM 2", 420, 300, 300, 200, "10.8 sqm"),
               ("BALCONY", 720, 0, 160, 500, "6.0 sqm")],
        area="Area: 72 sqm", beds="2 Bedroom",
        units_list=["#02-01", "#03-01", "#04-01", "#05-01"])
    paths.append(a1)
    b2 = hv / "harbour-view-type-b2.png"
    unit_plan_sheet(
        b2, "B2", "Harbour View — Type B2 Floor Plan",
        rooms=[("LIVING / DINING", 0, 0, 480, 320, "34.0 sqm"),
               ("MASTER BEDROOM", 480, 0, 340, 320, "18.6 sqm"),
               ("KITCHEN", 0, 320, 240, 220, "9.5 sqm"),
               ("BATH 1", 240, 320, 160, 220, "4.2 sqm"),
               ("BEDROOM 2", 400, 320, 220, 220, "11.0 sqm"),
               ("BEDROOM 3", 620, 320, 200, 220, "10.2 sqm"),
               ("BALCONY", 820, 0, 160, 540, "7.5 sqm")],
        area="Area: 96 sqm", beds="3 Bedroom",
        units_list=["#02-02", "#03-02", "#04-02", "#05-02", "#06-02"])
    paths.append(b2)
    site = hv / "harbour-view-site-map.png"
    site_map_sheet(site, "Harbour View — Unit Distribution",
                   [("#02-01", 120, 160, "A1"), ("#02-02", 320, 160, "B2"), ("#02-03", 520, 160, "C3"),
                    ("#03-01", 120, 320, "A1"), ("#03-02", 320, 320, "B2"), ("#03-03", 520, 320, "C3"),
                    ("#04-01", 120, 480, "A1"), ("#04-02", 320, 480, "B2"), ("#04-03", 520, 480, "C3")])
    paths.append(site)

    manifest = out / "manifest.jsonl"
    with manifest.open("w", encoding="utf-8") as f:
        f.write(json.dumps({"project": "harbour-view", "title": "Harbour View",
                            "description": "2 Bedroom, 3 Bedroom apartments",
                            "images": [str(p.relative_to(out)) for p in paths]}) + "\n")
    return paths


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    for p in generate(args.out):
        print("wrote", p)
    print("wrote", args.out / "manifest.jsonl")


if __name__ == "__main__":
    main()
